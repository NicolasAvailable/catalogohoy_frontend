-- Plantillas de reportes + más métricas en el snapshot.
--   · report_templates: un reporte guardado (título, métricas, periodo relativo)
--     que se vuelve a generar cuando el usuario quiera (p. ej. cada mes) con datos
--     nuevos. Cada generación crea una fila normal en `reports` (los anteriores
--     quedan) y cuenta para el límite mensual del plan como cualquier reporte.
--   · reports.template_id: de qué plantilla salió cada reporte (historial).
--   · build_report_snapshot ahora también devuelve: comparison (vs periodo
--     anterior), profit, channels, shipping, discounts, customers (nuevos vs
--     recurrentes) y weekdays. Los campos viejos no cambian.
-- Seguridad: RLS en la tabla nueva, mismo criterio que `reports`.

create table if not exists public.report_templates (
  id              bigint generated by default as identity primary key,
  tenant_id       bigint not null references public.tenants(id) on delete cascade,
  title           text not null,
  period_preset   text not null default 'previous_month'
                  check (period_preset in (
                    'last_7_days', 'last_30_days', 'last_90_days',
                    'previous_week', 'previous_month', 'current_month'
                  )),
  metrics_config  jsonb not null default '{}'::jsonb,
  created_by_auth_id uuid default auth.uid(),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create index if not exists report_templates_tenant_idx
  on public.report_templates (tenant_id);

alter table public.report_templates enable row level security;

drop policy if exists report_templates_tenant_all on public.report_templates;
create policy report_templates_tenant_all on public.report_templates
  for all to authenticated
  using (public._is_service_or_member(tenant_id))
  with check (public._is_service_or_member(tenant_id));

alter table public.reports
  add column if not exists template_id bigint
  references public.report_templates(id) on delete set null;

create index if not exists reports_template_idx
  on public.reports (template_id) where template_id is not null;

CREATE OR REPLACE FUNCTION public.build_report_snapshot(p_tenant_id bigint, p_period_start timestamp with time zone, p_period_end timestamp with time zone)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_orders_total        integer;
  v_orders_by_status    jsonb;
  v_sales_total         numeric;
  v_sales_total_bs      numeric;
  v_sales_by_day        jsonb;
  v_top_products        jsonb;
  v_top_customers       jsonb;
  v_payment_methods     jsonb;
  v_avg_ticket          numeric;
  -- Nuevas métricas
  v_prev_start          timestamptz;
  v_prev_orders         integer;
  v_prev_sales          numeric;
  v_has_costs           boolean;
  v_profit              jsonb;
  v_channels            jsonb;
  v_shipping            jsonb;
  v_discounts           jsonb;
  v_customers           jsonb;
  v_weekdays            jsonb;
BEGIN
  IF NOT public._is_service_or_member(p_tenant_id) THEN
    RAISE EXCEPTION 'not_a_member' USING ERRCODE = '42501';
  END IF;
  -- Total orders + breakdown by status. COUNT(*) over the grouped subquery
  -- would only count distinct statuses — we want the sum of the per-status
  -- counts (i.e. the real row count), so aggregate a second pass.
  SELECT COALESCE(SUM(cnt)::int, 0),
         COALESCE(jsonb_object_agg(status, cnt), '{}'::jsonb)
    INTO v_orders_total, v_orders_by_status
  FROM (
    SELECT COALESCE(status, 'pending') AS status, COUNT(*) AS cnt
    FROM public.orders
    WHERE tenant_id = p_tenant_id
      AND created_at >= p_period_start
      AND created_at <  p_period_end
    GROUP BY COALESCE(status, 'pending')
  ) s;

  SELECT COALESCE(SUM(total_usd), 0),
         COALESCE(SUM(total_bs), 0)
    INTO v_sales_total, v_sales_total_bs
  FROM public.orders
  WHERE tenant_id = p_tenant_id
    AND created_at >= p_period_start
    AND created_at <  p_period_end;

  v_avg_ticket := CASE
    WHEN v_orders_total > 0 THEN (v_sales_total / v_orders_total)::numeric
    ELSE 0
  END;

  SELECT COALESCE(
    jsonb_agg(jsonb_build_object('date', day, 'total', total_day) ORDER BY day),
    '[]'::jsonb
  ) INTO v_sales_by_day
  FROM (
    SELECT date_trunc('day', created_at)::date AS day,
           SUM(total_usd)::numeric            AS total_day
    FROM public.orders
    WHERE tenant_id = p_tenant_id
      AND created_at >= p_period_start
      AND created_at <  p_period_end
    GROUP BY 1
  ) d;

  SELECT COALESCE(
    jsonb_agg(jsonb_build_object(
      'productId', product_id,
      'name',      product_name,
      'photo',     product_photo,
      'quantity',  total_qty,
      'revenue',   total_rev
    ) ORDER BY total_qty DESC),
    '[]'::jsonb
  ) INTO v_top_products
  FROM (
    SELECT
      item->>'productId'  AS product_id,
      MAX(item->>'name')  AS product_name,
      MAX(item->>'photo') AS product_photo,
      SUM(COALESCE((item->>'quantity')::int, 0))  AS total_qty,
      SUM(COALESCE((item->>'total')::numeric, 0)) AS total_rev
    FROM public.orders o,
         jsonb_array_elements(COALESCE(o.products, '[]'::jsonb)) item
    WHERE o.tenant_id = p_tenant_id
      AND o.created_at >= p_period_start
      AND o.created_at <  p_period_end
      AND item->>'productId' IS NOT NULL
    GROUP BY item->>'productId'
    ORDER BY total_qty DESC
    LIMIT 10
  ) tp;

  SELECT COALESCE(
    jsonb_agg(jsonb_build_object(
      'name',          name,
      'phone',         phone,
      'ordersCount',   orders_count,
      'totalSpent',    total_spent,
      'totalSpentBs',  total_spent_bs
    ) ORDER BY total_spent DESC),
    '[]'::jsonb
  ) INTO v_top_customers
  FROM (
    SELECT
      MAX(name)                AS name,
      NULLIF(phone, '')        AS phone,
      COUNT(*)                 AS orders_count,
      SUM(total_usd)::numeric  AS total_spent,
      SUM(total_bs)::numeric   AS total_spent_bs
    FROM public.orders
    WHERE tenant_id = p_tenant_id
      AND created_at >= p_period_start
      AND created_at <  p_period_end
    GROUP BY NULLIF(phone, '')
    ORDER BY total_spent DESC
    LIMIT 10
  ) tc;

  SELECT COALESCE(
    jsonb_agg(jsonb_build_object(
      'method',        method,
      'ordersCount',   orders_count,
      'totalRevenue',  total_revenue
    ) ORDER BY orders_count DESC),
    '[]'::jsonb
  ) INTO v_payment_methods
  FROM (
    SELECT
      COALESCE(NULLIF(trim(payment_method), ''), 'Sin método') AS method,
      COUNT(*)                                                 AS orders_count,
      SUM(total_usd)::numeric                                  AS total_revenue
    FROM public.orders
    WHERE tenant_id = p_tenant_id
      AND created_at >= p_period_start
      AND created_at <  p_period_end
    GROUP BY COALESCE(NULLIF(trim(payment_method), ''), 'Sin método')
  ) pm;

  -- ── Comparación con el periodo anterior (misma duración, justo antes) ──
  v_prev_start := p_period_start - (p_period_end - p_period_start);
  SELECT COUNT(*)::int, COALESCE(SUM(total_usd), 0)
    INTO v_prev_orders, v_prev_sales
  FROM public.orders
  WHERE tenant_id = p_tenant_id
    AND created_at >= v_prev_start
    AND created_at <  p_period_start;

  -- ── Ganancia estimada: igual que Órdenes → Métricas. Ventas de producto −
  --    costo de producción ACTUAL × unidades − comisión. Sin canceladas ni
  --    rechazadas. Si la tienda no cargó costos, hasCosts = false.
  SELECT EXISTS (
    SELECT 1 FROM public.products
    WHERE tenant_id = p_tenant_id AND COALESCE(production_cost, 0) > 0
  ) INTO v_has_costs;

  WITH valid AS (
    SELECT o.id, o.products, COALESCE(o.commission, 0) AS commission
    FROM public.orders o
    WHERE o.tenant_id = p_tenant_id
      AND o.created_at >= p_period_start
      AND o.created_at <  p_period_end
      AND COALESCE(o.status, 'pending') NOT IN ('cancelled', 'rejected')
  ), lines AS (
    SELECT
      COALESCE((item->>'total')::numeric, 0) AS line_total,
      CASE
        WHEN COALESCE((item->>'isCustom')::boolean, false) THEN 0
        ELSE COALESCE(p.production_cost, 0) * COALESCE((item->>'quantity')::numeric, 0)
      END AS line_cost
    FROM valid v
    CROSS JOIN LATERAL jsonb_array_elements(COALESCE(v.products, '[]'::jsonb)) item
    LEFT JOIN public.products p
      ON p.tenant_id = p_tenant_id
     AND p.id::text = item->>'productId'
     AND COALESCE(p.production_cost, 0) > 0
  )
  SELECT jsonb_build_object(
    'hasCosts',   v_has_costs,
    'revenue',    COALESCE((SELECT SUM(line_total) FROM lines), 0),
    'cost',       COALESCE((SELECT SUM(line_cost)  FROM lines), 0),
    'commission', COALESCE((SELECT SUM(commission) FROM valid), 0),
    'profit',     COALESCE((SELECT SUM(line_total) - SUM(line_cost) FROM lines), 0)
                  - COALESCE((SELECT SUM(commission) FROM valid), 0)
  ) INTO v_profit;

  -- ── Canal de venta (catálogo público, manual, punto de venta) ──
  SELECT COALESCE(
    jsonb_agg(jsonb_build_object(
      'channel', channel, 'ordersCount', cnt, 'total', total
    ) ORDER BY total DESC),
    '[]'::jsonb
  ) INTO v_channels
  FROM (
    SELECT COALESCE(NULLIF(source, ''), 'public') AS channel,
           COUNT(*) AS cnt,
           COALESCE(SUM(total_usd), 0)::numeric AS total
    FROM public.orders
    WHERE tenant_id = p_tenant_id
      AND created_at >= p_period_start
      AND created_at <  p_period_end
    GROUP BY 1
  ) ch;

  -- ── Métodos de entrega + total cobrado en envíos ──
  SELECT jsonb_build_object(
    'totalFees', COALESCE((
      SELECT SUM(COALESCE(shipping_fee, (shipping_method->>'fee')::numeric, 0))
      FROM public.orders
      WHERE tenant_id = p_tenant_id
        AND created_at >= p_period_start
        AND created_at <  p_period_end
    ), 0),
    'methods', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'name', name, 'type', type, 'ordersCount', cnt
      ) ORDER BY cnt DESC)
      FROM (
        SELECT COALESCE(NULLIF(shipping_method->>'name', ''), 'Sin método de entrega') AS name,
               shipping_method->>'type' AS type,
               COUNT(*) AS cnt
        FROM public.orders
        WHERE tenant_id = p_tenant_id
          AND created_at >= p_period_start
          AND created_at <  p_period_end
        GROUP BY 1, 2
      ) sm
    ), '[]'::jsonb)
  ) INTO v_shipping;

  -- ── Descuentos ──
  SELECT jsonb_build_object(
    'total', COALESCE(SUM(COALESCE(discount_amount, 0)), 0),
    'ordersCount', COUNT(*) FILTER (WHERE COALESCE(discount_amount, 0) > 0),
    'codes', COALESCE((
      SELECT jsonb_agg(jsonb_build_object('code', code, 'uses', uses, 'total', total)
                       ORDER BY uses DESC)
      FROM (
        SELECT upper(trim(discount_code)) AS code,
               COUNT(*) AS uses,
               COALESCE(SUM(discount_amount), 0) AS total
        FROM public.orders
        WHERE tenant_id = p_tenant_id
          AND created_at >= p_period_start
          AND created_at <  p_period_end
          AND NULLIF(trim(discount_code), '') IS NOT NULL
        GROUP BY 1
        ORDER BY 2 DESC
        LIMIT 10
      ) dc
    ), '[]'::jsonb)
  ) INTO v_discounts
  FROM public.orders
  WHERE tenant_id = p_tenant_id
    AND created_at >= p_period_start
    AND created_at <  p_period_end;

  -- ── Clientes nuevos vs recurrentes (por teléfono). Nuevo = su primera
  --    orden en la tienda cae dentro del periodo.
  WITH firsts AS (
    SELECT NULLIF(regexp_replace(phone, '\D', '', 'g'), '') AS ph,
           MIN(created_at) AS first_at,
           bool_or(created_at >= p_period_start) AS in_period
    FROM public.orders
    WHERE tenant_id = p_tenant_id
      AND created_at < p_period_end
    GROUP BY 1
  )
  SELECT jsonb_build_object(
    'total',     COUNT(*),
    'new',       COUNT(*) FILTER (WHERE first_at >= p_period_start),
    'returning', COUNT(*) FILTER (WHERE first_at <  p_period_start)
  ) INTO v_customers
  FROM firsts
  WHERE ph IS NOT NULL AND in_period;

  -- ── Ventas por día de la semana (0 = domingo … 6 = sábado) ──
  SELECT COALESCE(
    jsonb_agg(jsonb_build_object('weekday', wd, 'ordersCount', cnt, 'total', total)
              ORDER BY wd),
    '[]'::jsonb
  ) INTO v_weekdays
  FROM (
    SELECT EXTRACT(dow FROM created_at)::int AS wd,
           COUNT(*) AS cnt,
           COALESCE(SUM(total_usd), 0)::numeric AS total
    FROM public.orders
    WHERE tenant_id = p_tenant_id
      AND created_at >= p_period_start
      AND created_at <  p_period_end
    GROUP BY 1
  ) w;

  RETURN jsonb_build_object(
    'period', jsonb_build_object(
      'start', p_period_start,
      'end',   p_period_end
    ),
    'orders', jsonb_build_object(
      'total',    v_orders_total,
      'byStatus', v_orders_by_status
    ),
    'sales', jsonb_build_object(
      'total',     v_sales_total,
      'totalBs',   v_sales_total_bs,
      'avgTicket', v_avg_ticket,
      'byDay',     v_sales_by_day
    ),
    'topProducts',    v_top_products,
    'topCustomers',   v_top_customers,
    'paymentMethods', v_payment_methods,
    'comparison', jsonb_build_object(
      'previousStart', v_prev_start,
      'previousEnd',   p_period_start,
      'orders',        v_prev_orders,
      'sales',         v_prev_sales,
      'avgTicket',     CASE WHEN v_prev_orders > 0 THEN v_prev_sales / v_prev_orders ELSE 0 END
    ),
    'profit',    v_profit,
    'channels',  v_channels,
    'shipping',  v_shipping,
    'discounts', v_discounts,
    'customers', v_customers,
    'weekdays',  v_weekdays
  );
END;
$function$;
